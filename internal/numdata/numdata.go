// Package numdata is the model layer for number formatting: what a locale's
// number data holds, and how it is written down.
//
// It sits between the generator and the library so that the two share one
// definition rather than each spelling the layout out. Nothing here formats
// anything. What is stored is what CLDR says -- the symbols a locale writes
// numbers with and the patterns it writes them in, as patterns -- and never
// what any of it produces. A field holding a formatted number would mean the
// layering had been violated.
package numdata

import (
	"fmt"
	"sort"

	"github.com/go-quickjs/go-intl/internal/blob"
)

// Version is the encoding's version, written first so that data generated by
// an older command is refused rather than misread.
const Version = 2

// A Currency is what one currency is called in one locale.
type Currency struct {
	// Code is the ISO code, "EUR".
	Code string
	// Symbol is what the locale writes instead, and Narrow the shorter form
	// where the locale has one. Either may be empty, in which case the code
	// itself is written.
	Symbol string
	Narrow string
	// DisplayName is what the currency is called on its own, "US Dollar",
	// which is not the same as any of the counted wordings: those go beside an
	// amount and this one does not.
	DisplayName string
	// Names are the spelled-out names, one per plural category: a dollar and
	// two dollars are not the same word, and in Polish there are four.
	Names []CountedText
}

// A CountedText is a wording and the plural category it belongs to.
type CountedText struct {
	Count string
	Text  string
}

// Name returns the spelled-out name for a plural category, falling back to
// "other" as CLDR's own lookup does.
func (c Currency) Name(count string) string {
	var other string
	for _, n := range c.Names {
		if n.Count == count {
			return n.Text
		}
		if n.Count == "other" {
			other = n.Text
		}
	}
	return other
}

// Symbols are the marks a locale writes numbers with.
type Symbols struct {
	Decimal     string
	Group       string
	PercentSign string
	PlusSign    string
	MinusSign   string
	Exponential string
	NaN         string
	Infinity    string
	// CurrencyDecimal and CurrencyGroup are used in place of Decimal and Group
	// when money is written, where a locale distinguishes them. Empty means it
	// does not.
	CurrencyDecimal string
	CurrencyGroup   string
}

// Spacing is one of CLDR's currency-spacing rules: when a space has to be put
// between the currency and the number because neither side supplies one.
//
// "USD1.00" reads badly where "$1.00" does not, so CLDR says to insert a space
// when the character of the currency facing the number is neither a symbol nor
// a separator, and the character of the number facing it is a digit. The
// patterns are Unicode set expressions and are kept as CLDR writes them.
type Spacing struct {
	CurrencyMatch    string
	SurroundingMatch string
	InsertBetween    string
}

// A CompactPattern is one of the short or long forms a magnitude is written
// in: "0K" for a thousand, "0 million" for a million. Count is the plural
// category it applies to, since a language may write a million differently
// depending on how many there are.
type CompactPattern struct {
	Exponent int
	Count    string
	Pattern  string
}

// A System is how a locale writes numbers in one numbering system: the digits,
// the marks and the patterns. Arabic writes Latin digits by default and Arabic
// ones when asked, with different separators for each.
type System struct {
	// NumberingSystem is the name of the digits, "latn" or "arab", and
	// Digits are those ten digits. Digits is empty when they are the ASCII
	// ones, which is most of the time.
	NumberingSystem string
	Digits          string

	Symbols Symbols

	// The patterns, as UTS #35 writes them: "#,##0.###", "¤#,##0.00".
	// They are kept as patterns and taken apart when a formatter is built,
	// because a pattern is a rule and what it produces is an answer.
	DecimalPattern    string
	PercentPattern    string
	CurrencyPattern   string
	AccountingPattern string

	// BeforeCurrency applies where the currency follows the number, and
	// AfterCurrency where it comes first.
	BeforeCurrency Spacing
	AfterCurrency  Spacing

	// CompactShort and CompactLong are the compact forms, sorted by exponent.
	CompactShort []CompactPattern
	CompactLong  []CompactPattern
}

// Locale is everything needed to write a number in one locale.
type Locale struct {
	// System is the numbering system in use: the locale's default as the
	// data is read, and whichever one Select chose after.
	System
	// Others are the locale's other numbering systems, sorted by name.
	Others []System
	// Partials are what the locale says about systems it does not use: a few
	// marks or patterns, with every other field empty. Persian writes an "E"
	// for the exponent in Arabic digits where the root would write "اس".
	// Sorted by name.
	Partials []System

	// MinimumGroupingDigits is how many digits the first group must have for
	// a separator to appear at all: two in Spanish and Polish, where 1234 is
	// written without one.
	MinimumGroupingDigits int

	// UnitPatterns join an amount to a spelled-out currency name, "{0} {1}",
	// one per plural category.
	UnitPatterns []CountedText

	// Currencies is sorted by code.
	Currencies []Currency
}

// Currency finds one currency's names.
func (l *Locale) Currency(code string) (Currency, bool) {
	i := sort.Search(len(l.Currencies), func(i int) bool {
		return l.Currencies[i].Code >= code
	})
	if i < len(l.Currencies) && l.Currencies[i].Code == code {
		return l.Currencies[i], true
	}
	return Currency{}, false
}

// A NumberingSystem is one of CLDR's numeric systems -- ten digits, used in
// place of 0 to 9 -- with what the root says about writing numbers in it.
//
// The root gives a few systems marks and patterns of their own: Arabic digits
// take the Arabic decimal separator in any locale. For the rest, the root
// points back at the asking locale's Latin data, so Devanagari digits in
// English are written with English separators. Where a field here is empty or
// nil, that is what it means.
type NumberingSystem struct {
	Name   string
	Digits string

	Symbols *Symbols

	DecimalPattern    string
	PercentPattern    string
	CurrencyPattern   string
	AccountingPattern string
}

// Select returns the locale as written in another numbering system, from
// what the locale has for it or else from the root's entry. It reports false
// for a system that is neither, which is not one a number can be written in.
func (l *Locale) Select(name string, systems []NumberingSystem) (*Locale, bool) {
	if name == l.NumberingSystem {
		return l, true
	}
	for _, s := range l.Others {
		if s.NumberingSystem == name {
			out := *l
			out.System = s
			return &out, true
		}
	}
	i := sort.Search(len(systems), func(i int) bool { return systems[i].Name >= name })
	if i == len(systems) || systems[i].Name != name {
		return nil, false
	}
	root := systems[i]
	// The root's own entry, over the locale's Latin data.
	latin := l.System
	for _, s := range l.Others {
		if s.NumberingSystem == "latn" {
			latin = s
		}
	}
	out := *l
	out.System = latin
	out.NumberingSystem = root.Name
	out.Digits = root.Digits
	if root.Symbols != nil {
		out.Symbols = *root.Symbols
	}
	for _, f := range []struct {
		dst *string
		src string
	}{
		{&out.DecimalPattern, root.DecimalPattern},
		{&out.PercentPattern, root.PercentPattern},
		{&out.CurrencyPattern, root.CurrencyPattern},
		{&out.AccountingPattern, root.AccountingPattern},
	} {
		if f.src != "" {
			*f.dst = f.src
		}
	}
	// And the locale's own word on the system, field by field, over both:
	// ICU looks each one up through the locale before the root.
	for i := range l.Partials {
		if l.Partials[i].NumberingSystem != name {
			continue
		}
		partial := l.Partials[i]
		dst, src := out.System.fields(), partial.fields()
		for j := 2; j < len(dst); j++ {
			if *src[j] != "" {
				*dst[j] = *src[j]
			}
		}
	}
	return &out, true
}

// Encode writes a locale's data.
//
// The layout is a version byte and then length-prefixed strings in a fixed
// order, which the blob package writes. It is deliberately dull: the seam that
// matters is the Source the bytes arrive through, not a clever encoding.
func Encode(l *Locale) []byte {
	w := blob.NewWriter(Version)
	encodeSystem(w, &l.System)
	for _, set := range [][]System{l.Others, l.Partials} {
		w.Uint(len(set))
		for i := range set {
			encodeSystem(w, &set[i])
		}
	}
	w.Uint(l.MinimumGroupingDigits)
	w.Uint(len(l.UnitPatterns))
	for _, u := range l.UnitPatterns {
		w.String(u.Count)
		w.String(u.Text)
	}
	w.Uint(len(l.Currencies))
	for _, c := range l.Currencies {
		w.String(c.Code)
		w.String(c.Symbol)
		w.String(c.Narrow)
		w.String(c.DisplayName)
		w.Uint(len(c.Names))
		for _, n := range c.Names {
			w.String(n.Count)
			w.String(n.Text)
		}
	}
	return w.Bytes()
}

// Decode reads what Encode wrote.
func Decode(b []byte) (*Locale, error) {
	r, err := blob.NewReader(b, Version)
	if err != nil {
		return nil, err
	}
	var l Locale
	decodeSystem(r, &l.System)
	for _, set := range []*[]System{&l.Others, &l.Partials} {
		n := r.Uint()
		if n < 0 || n > r.Left() {
			break
		}
		if n > 0 {
			*set = make([]System, n)
		}
		for i := range *set {
			decodeSystem(r, &(*set)[i])
		}
	}
	l.MinimumGroupingDigits = r.Uint()

	if n := r.Uint(); n >= 0 && n <= r.Left() {
		l.UnitPatterns = make([]CountedText, 0, n)
		for i := 0; i < n; i++ {
			count := r.String()
			text := r.String()
			l.UnitPatterns = append(l.UnitPatterns, CountedText{count, text})
		}
	}
	if n := r.Uint(); n >= 0 && n <= r.Left() {
		l.Currencies = make([]Currency, 0, n)
		for i := 0; i < n; i++ {
			var c Currency
			c.Code = r.String()
			c.Symbol = r.String()
			c.Narrow = r.String()
			c.DisplayName = r.String()
			names := r.Uint()
			if names < 0 || names > r.Left() {
				break
			}
			c.Names = make([]CountedText, 0, names)
			for j := 0; j < names; j++ {
				count := r.String()
				text := r.String()
				c.Names = append(c.Names, CountedText{count, text})
			}
			l.Currencies = append(l.Currencies, c)
		}
	}
	if err := r.Err(); err != nil {
		return nil, err
	}
	return &l, nil
}

// fields are a system's string fields in the order they are written. Encode
// and Decode both walk this, so neither can add a field without the other.
func (s *System) fields() []*string {
	return []*string{
		&s.NumberingSystem, &s.Digits,
		&s.Symbols.Decimal, &s.Symbols.Group, &s.Symbols.PercentSign,
		&s.Symbols.PlusSign, &s.Symbols.MinusSign, &s.Symbols.Exponential,
		&s.Symbols.NaN, &s.Symbols.Infinity,
		&s.Symbols.CurrencyDecimal, &s.Symbols.CurrencyGroup,
		&s.DecimalPattern, &s.PercentPattern, &s.CurrencyPattern, &s.AccountingPattern,
		&s.BeforeCurrency.CurrencyMatch, &s.BeforeCurrency.SurroundingMatch,
		&s.BeforeCurrency.InsertBetween,
		&s.AfterCurrency.CurrencyMatch, &s.AfterCurrency.SurroundingMatch,
		&s.AfterCurrency.InsertBetween,
	}
}

func encodeSystem(w *blob.Writer, s *System) {
	for _, p := range s.fields() {
		w.String(*p)
	}
	for _, set := range [][]CompactPattern{s.CompactShort, s.CompactLong} {
		w.Uint(len(set))
		for _, c := range set {
			w.Uint(c.Exponent)
			w.String(c.Count)
			w.String(c.Pattern)
		}
	}
}

func decodeSystem(r *blob.Reader, s *System) {
	for _, p := range s.fields() {
		*p = r.String()
	}
	for _, set := range []*[]CompactPattern{&s.CompactShort, &s.CompactLong} {
		n := r.Uint()
		if n < 0 || n > r.Left() {
			break
		}
		out := make([]CompactPattern, 0, n)
		for i := 0; i < n; i++ {
			exponent := r.Uint()
			count := r.String()
			pattern := r.String()
			out = append(out, CompactPattern{exponent, count, pattern})
		}
		*set = out
	}
}

// EncodeSystems writes the numbering systems table, sorted by name.
func EncodeSystems(systems []NumberingSystem) []byte {
	w := blob.NewWriter(Version)
	w.Uint(len(systems))
	for _, s := range systems {
		w.String(s.Name)
		w.String(s.Digits)
		if s.Symbols == nil {
			w.Uint(0)
		} else {
			w.Uint(1)
			sys := System{Symbols: *s.Symbols}
			for _, p := range sys.fields()[2:12] {
				w.String(*p)
			}
		}
		w.String(s.DecimalPattern)
		w.String(s.PercentPattern)
		w.String(s.CurrencyPattern)
		w.String(s.AccountingPattern)
	}
	return w.Bytes()
}

// DecodeSystems reads what EncodeSystems wrote.
func DecodeSystems(b []byte) ([]NumberingSystem, error) {
	r, err := blob.NewReader(b, Version)
	if err != nil {
		return nil, err
	}
	n := r.Uint()
	if n > r.Left() {
		return nil, fmt.Errorf("numdata: %d numbering systems with %d bytes left", n, r.Left())
	}
	out := make([]NumberingSystem, 0, n)
	for i := 0; i < n; i++ {
		var s NumberingSystem
		s.Name = r.String()
		s.Digits = r.String()
		if r.Uint() == 1 {
			var sys System
			for _, p := range sys.fields()[2:12] {
				*p = r.String()
			}
			s.Symbols = &sys.Symbols
		}
		s.DecimalPattern = r.String()
		s.PercentPattern = r.String()
		s.CurrencyPattern = r.String()
		s.AccountingPattern = r.String()
		out = append(out, s)
	}
	if err := r.Err(); err != nil {
		return nil, err
	}
	return out, nil
}
